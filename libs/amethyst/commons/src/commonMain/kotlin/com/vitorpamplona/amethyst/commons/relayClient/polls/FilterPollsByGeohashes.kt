package com.vitorpamplona.amethyst.commons.relayClient.polls

import com.vitorpamplona.amethyst.commons.model.topNavFeeds.aroundMe.LocationTopNavPerRelayFilterSet
import com.vitorpamplona.amethyst.commons.relayClient.subscriptions.ExplainedFilter
import com.vitorpamplona.amethyst.commons.relayClient.subscriptions.SubPurpose
import com.vitorpamplona.amethyst.commons.relays.SincePerRelayMap
import com.vitorpamplona.quartz.experimental.zapPolls.ZapPollEvent
import com.vitorpamplona.quartz.nip01Core.relay.client.pool.RelayBasedFilter
import com.vitorpamplona.quartz.nip01Core.relay.normalizer.NormalizedRelayUrl
import com.vitorpamplona.quartz.nip88Polls.poll.PollEvent

fun filterPollsByGeohashes(
    relay: NormalizedRelayUrl,
    geotags: Set<String>,
    since: Long?,
): List<RelayBasedFilter> {
    if (geotags.isEmpty()) return emptyList()

    return listOf(
        RelayBasedFilter(
            relay = relay,
            filter =
                ExplainedFilter(
                    purpose = SubPurpose.TAG_FEED,
                    kinds = listOf(PollEvent.KIND, ZapPollEvent.KIND),
                    tags = mapOf("g" to geotags.sorted()),
                    limit = 100,
                    since = since,
                ),
        ),
    )
}

fun filterPollsByGeohashes(
    geoSet: LocationTopNavPerRelayFilterSet,
    since: SincePerRelayMap?,
    defaultSince: Long?,
): List<RelayBasedFilter> {
    if (geoSet.set.isEmpty()) return emptyList()

    return geoSet.set
        .mapNotNull {
            if (it.value.geotags.isEmpty()) {
                null
            } else {
                filterPollsByGeohashes(
                    relay = it.key,
                    geotags = it.value.geotags,
                    since = since?.get(it.key)?.time ?: defaultSince,
                )
            }
        }.flatten()
}
